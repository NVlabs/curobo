@dataclass(frozen=True)
class TrajOptResultProcessorConfig:
    """Static configuration for trajectory-optimization result processing."""

    #: Device used for shape-dependent workspaces.
    device_cfg: DeviceCfg

    #: Number of optimized action timesteps.
    action_horizon: int

    #: Number of state timesteps generated by the metrics rollout.
    horizon: int

    #: Number of optimized robot degrees of freedom.
    action_dim: int

    #: Number of interpolated timesteps per optimized action timestep.
    interpolation_steps: int

    #: Maximum number of goal-set indices stored per seed.
    goalset_index_dim: int

    #: Data type used by goal-set indices.
    goalset_index_dtype: torch.dtype

    #: Ordered names of the optimized robot joints.
    joint_names: Sequence[str]

    #: Position-error threshold used to determine convergence.
    position_tolerance: float

    #: Orientation-error threshold used to determine convergence.
    orientation_tolerance: float

    #: Minimum allowed trajectory timestep.
    minimum_trajectory_dt: float

    #: Maximum allowed trajectory timestep.
    maximum_trajectory_dt: float

    #: Capture steady-state candidate updates and finalization in CUDA graphs.
    use_cuda_graph: bool = True


@dataclass
class TrajOptResultCandidate:
    """Transient inputs produced for one trajectory-optimization finetune attempt."""

    #: Metrics for the optimized knot trajectory with flattened batch and seed dimensions.
    metrics: RolloutMetrics

    #: Metrics for the interpolated trajectory with flattened batch and seed dimensions.
    interpolated_metrics: Optional[RolloutMetrics]

    #: Debug information attached to the returned solver result.
    debug_info: Dict


@dataclass(frozen=True)
class TrajOptResultUpdate:
    """State returned after processing one finetune candidate."""

    #: Whether at least one candidate replaced the existing best trajectory.
    improved: bool

    #: Whether the accumulated result contains at least one successful trajectory.
    any_success: bool

    #: Best trajectory timesteps shaped ``[batch, num_seeds]``.
    best_dt: torch.Tensor

    #: Optimized actions for the next attempt, shaped ``[batch * num_seeds, horizon, dof]``.
    next_seed: torch.Tensor


@dataclass
class _TrajOptResultSnapshot:
    """Minimal shape-managed state retained across finetune candidates."""

    #: Optimized actions shaped ``[batch, num_seeds, action_horizon, dof]``.
    actions: torch.Tensor

    #: Rolled-out knot state shaped ``[batch, num_seeds, horizon, dof]``.
    js_solution: JointState

    #: Success mask shaped ``[batch, num_seeds]``.
    success: torch.Tensor

    #: Final position error shaped ``[batch, num_seeds]``.
    position_error: torch.Tensor

    #: Final rotation error shaped ``[batch, num_seeds]``.
    rotation_error: torch.Tensor

    #: Goal-set indices shaped ``[batch, num_seeds, max_num_links]``.
    goalset_index: torch.Tensor

    #: Pose rollout cost shaped ``[batch, num_seeds]``.
    seed_cost: torch.Tensor

    #: Debug information retained from the first candidate.
    debug_info: Dict


@dataclass(frozen=True)
class _ConvergenceLayout:
    """Cached indices for the stable rollout convergence-term layout."""

    position_indices: tuple[int, ...]
    orientation_indices: tuple[int, ...]
    goalset_indices: tuple[int, ...]


@dataclass(frozen=True)
class _ProcessedTrajOptCandidate:
    """Per-seed fields extracted from one transient rollout candidate."""

    actions: torch.Tensor
    js_solution: JointState
    success: torch.Tensor
    position_error: torch.Tensor
    rotation_error: torch.Tensor
    goalset_index: Optional[torch.Tensor]
    seed_cost: torch.Tensor
    debug_info: Dict


class TrajOptResultProcessor(Protocol):
    """Interface for stateful trajectory-optimization result processing."""

    @property
    def best_dt(self) -> torch.Tensor:
        """Return the best timestep workspace shaped ``[batch, num_seeds]``."""

    def reset_shape(self) -> None:
        """Invalidate all shape-dependent workspaces."""

    def update_batch_size(
        self,
        batch_size: int,
        num_seeds: int,
        return_seeds: int,
    ) -> None:
        """Create or resize all shape-dependent workspaces."""

    def reset_cuda_graph(self) -> None:
        """Invalidate captured work while preserving shape-dependent workspaces."""

    def reset(self, initial_dt: torch.Tensor) -> None:
        """Reset per-solve state using ``initial_dt`` shaped ``[batch, num_seeds]``."""

    def update(self, candidate: TrajOptResultCandidate) -> TrajOptResultUpdate:
        """Process one candidate without changing the configured shape."""

    def get_interpolation_input(self) -> JointState:
        """Return a borrowed all-seed state for external final interpolation."""

    def finalize(
        self,
        return_seeds: int,
        interpolated_trajectory: JointState,
        interpolated_last_tstep: torch.Tensor,
        timeopt_success: Optional[torch.Tensor] = None,
        timeopt_duration: Optional[torch.Tensor] = None,
    ) -> TrajOptSolverResult:
        """Rank candidates and gather knot and externally interpolated trajectories.

        CUDA-graph implementations may return borrowed output buffers that remain
        valid only until the next finalization with the same processor.
        """


class TorchTrajOptResultProcessor:
    """Torch trajectory-result accumulation with optional CUDA-graph replay.

    With CUDA graphs enabled, finalized tensor outputs borrow graph-owned buffers
    and remain valid until the next finalization. Eager outputs remain independently
    owned tensors.
    """

    def __init__(
        self,
        config: TrajOptResultProcessorConfig,
        get_full_dof_from_solution: Callable[[JointState], JointState],
    ) -> None:
        """Store static configuration without creating shape-dependent tensors."""
        self._config = config
        self._get_full_dof_from_solution = get_full_dof_from_solution
        self._use_cuda_graph = (
            config.use_cuda_graph
            and config.device_cfg.device.type == "cuda"
            and curobo_runtime.cuda_graphs
        )
        self._batch_size = 0
        self._num_seeds = 0
        self._return_seeds = 0
        self._best_dt: Optional[torch.Tensor] = None
        self._batch_seed_offsets: Optional[torch.Tensor] = None
        self._flat_seed_indices: Optional[torch.Tensor] = None
        self._snapshot: Optional[_TrajOptResultSnapshot] = None
        self._seed_rank: Optional[torch.Tensor] = None
        self._total_cost: Optional[torch.Tensor] = None
        self._convergence_names: Optional[tuple[str, ...]] = None
        self._convergence_layout: Optional[_ConvergenceLayout] = None
        self._goalset_index_count = 0
        self._has_result = False
        self._any_success = False
        self._is_ranked = False
        self._bound_candidate: Optional[TrajOptResultCandidate] = None
        self._bound_interpolated_trajectory: Optional[JointState] = None
        self._initial_update_graph: Optional[GraphExecutor] = None
        self._masked_update_graph: Optional[GraphExecutor] = None
        self._finalize_graph: Optional[GraphExecutor] = None
        self._final_result: Optional[TrajOptSolverResult] = None
        self._final_success: Optional[torch.Tensor] = None
        self._timeopt_duration: Optional[torch.Tensor] = None

    @property
    def batch_size(self) -> int:
        """Return the configured logical batch size."""
        return self._batch_size

    @property
    def num_seeds(self) -> int:
        """Return the configured number of seeds per problem."""
        return self._num_seeds

    @property
    def return_seeds(self) -> int:
        """Return the configured number of seeds selected at finalization."""
        return self._return_seeds

    @property
    def is_shape_initialized(self) -> bool:
        """Return whether shape-dependent workspaces are initialized."""
        return self._best_dt is not None

    @property
    def is_cuda_graph_initialized(self) -> bool:
        """Return whether all steady-state processor graphs have been captured."""
        executors = (
            self._initial_update_graph,
            self._masked_update_graph,
            self._finalize_graph,
        )
        return all(executor is not None and executor.is_initialized for executor in executors)

    @property
    def best_dt(self) -> torch.Tensor:
        """Return the best timestep workspace shaped ``[batch, num_seeds]``."""
        self._require_shape_initialized()
        return self._best_dt

    @profiler.record_function("trajopt_result_processor/reset_shape")
    def reset_shape(self) -> None:
        """Invalidate all shape-dependent workspaces and accumulated state."""
        self.reset_cuda_graph()
        self._batch_size = 0
        self._num_seeds = 0
        self._return_seeds = 0
        self._best_dt = None
        self._batch_seed_offsets = None
        self._flat_seed_indices = None
        self._snapshot = None
        self._seed_rank = None
        self._total_cost = None
        self._convergence_names = None
        self._convergence_layout = None
        self._goalset_index_count = 0
        self._has_result = False
        self._any_success = False
        self._is_ranked = False

    @profiler.record_function("trajopt_result_processor/reset_cuda_graph")
    def reset_cuda_graph(self) -> None:
        """Invalidate captured work and its statically bound input objects."""
        for executor in (
            self._initial_update_graph,
            self._masked_update_graph,
            self._finalize_graph,
        ):
            if executor is not None:
                executor.reset()
        self._initial_update_graph = None
        self._masked_update_graph = None
        self._finalize_graph = None
        self._bound_candidate = None
        self._bound_interpolated_trajectory = None
        self._final_result = None

    @profiler.record_function("trajopt_result_processor/update_batch_size")
    def update_batch_size(
        self,
        batch_size: int,
        num_seeds: int,
        return_seeds: int,
    ) -> None:
        """Create workspaces for ``batch_size`` problems and ``num_seeds`` seeds."""
        if batch_size < 1:
            log_and_raise(f"batch_size must be positive, received {batch_size}")
        if num_seeds < 1:
            log_and_raise(f"num_seeds must be positive, received {num_seeds}")
        if return_seeds < 1 or return_seeds > num_seeds:
            log_and_raise(
                f"return_seeds must be in [1, {num_seeds}], received {return_seeds}"
            )
        if (
            self._best_dt is not None
            and self._batch_size == batch_size
            and self._num_seeds == num_seeds
            and self._return_seeds == return_seeds
        ):
            return

        self.reset_shape()
        self._batch_size = batch_size
        self._num_seeds = num_seeds
        self._return_seeds = return_seeds
        js_solution = self._create_joint_state_workspace(self._config.horizon)
        self._snapshot = _TrajOptResultSnapshot(
            actions=torch.empty(
                (batch_size, num_seeds, self._config.action_horizon, self._config.action_dim),
                device=self._config.device_cfg.device,
                dtype=self._config.device_cfg.dtype,
            ),
            js_solution=js_solution,
            success=torch.empty(
                (batch_size, num_seeds),
                device=self._config.device_cfg.device,
                dtype=torch.bool,
            ),
            position_error=torch.empty(
                (batch_size, num_seeds),
                device=self._config.device_cfg.device,
                dtype=self._config.device_cfg.dtype,
            ),
            rotation_error=torch.empty(
                (batch_size, num_seeds),
                device=self._config.device_cfg.device,
                dtype=self._config.device_cfg.dtype,
            ),
            goalset_index=torch.empty(
                (batch_size, num_seeds, self._config.goalset_index_dim),
                device=self._config.device_cfg.device,
                dtype=self._config.goalset_index_dtype,
            ),
            seed_cost=torch.empty(
                (batch_size, num_seeds),
                device=self._config.device_cfg.device,
                dtype=self._config.device_cfg.dtype,
            ),
            debug_info={},
        )
        self._best_dt = js_solution.dt
        self._batch_seed_offsets = (
            torch.arange(
                batch_size,
                device=self._config.device_cfg.device,
                dtype=torch.long,
            ).view(-1, 1)
            * num_seeds
        )
        self._flat_seed_indices = torch.empty(
            batch_size * num_seeds,
            device=self._config.device_cfg.device,
            dtype=torch.long,
        )

    @profiler.record_function("trajopt_result_processor/reset")
    def reset(self, initial_dt: torch.Tensor) -> None:
        """Reset accumulated candidates without changing workspace shapes."""
        self._require_shape_initialized()
        expected_shape = (self._batch_size, self._num_seeds)
        if initial_dt.shape != expected_shape:
            log_and_raise(f"initial_dt.shape: {initial_dt.shape} != {expected_shape}")
        self._best_dt.copy_(initial_dt)
        self._snapshot.debug_info = {}
        self._seed_rank = None
        self._total_cost = None
        self._goalset_index_count = 0
        self._has_result = False
        self._any_success = False
        self._is_ranked = False

    @profiler.record_function("trajopt_result_processor/update")
    def update(self, candidate: TrajOptResultCandidate) -> TrajOptResultUpdate:
        """Process and accumulate one finetune candidate using the configured shape."""
        self._require_shape_initialized()
        self._validate_candidate_shape(candidate)
        if self._use_cuda_graph:
            return self._update_with_cuda_graph(candidate)

        candidate_result = self._process_candidate_metrics(candidate)

        improved = True
        if not self._has_result:
            self._copy_candidate_result(candidate_result, copy_debug=True)
            self._has_result = True
            self._any_success = bool(torch.any(self._snapshot.success).item())
            self._invalidate_rank()
        else:
            update_mask = torch.logical_and(
                candidate_result.success,
                candidate_result.js_solution.dt <= self._best_dt,
            )
            batch_indices, seed_indices = update_mask.nonzero(as_tuple=True)
            improved = batch_indices.numel() > 0
            if improved:
                if batch_indices.numel() == update_mask.numel():
                    self._copy_candidate_result(candidate_result)
                else:
                    self._copy_candidate_result(
                        candidate_result,
                        batch_indices,
                        seed_indices,
                    )
                self._any_success = True
                self._invalidate_rank()

        next_seed = self._snapshot.actions.view(
            self._batch_size * self._num_seeds,
            self._config.action_horizon,
            self._config.action_dim,
        )
        return TrajOptResultUpdate(
            improved=improved,
            any_success=self._any_success,
            best_dt=self._best_dt,
            next_seed=next_seed,
        )

    def _update_with_cuda_graph(
        self,
        candidate: TrajOptResultCandidate,
    ) -> TrajOptResultUpdate:
        """Replay a fixed-shape initial or masked candidate-update graph."""
        names = tuple(candidate.metrics.convergence.names)
        bindings_changed = (
            self._bound_candidate is None
            or self._bound_candidate.metrics is not candidate.metrics
            or self._bound_candidate.interpolated_metrics is not candidate.interpolated_metrics
            or names != self._convergence_names
        )
        if bindings_changed:
            self.reset_cuda_graph()
            self._bound_candidate = TrajOptResultCandidate(
                metrics=candidate.metrics,
                interpolated_metrics=candidate.interpolated_metrics,
                debug_info={},
            )

        layout = self._get_convergence_layout(candidate.metrics)
        problem_count = self._batch_size * self._num_seeds
        goalset_index_count = sum(
            candidate.metrics.convergence.values[index][:, -1].numel() // problem_count
            for index in layout.goalset_indices
        )
        if goalset_index_count > self._config.goalset_index_dim:
            log_and_raise(
                "candidate goalset index dimension exceeds configured workspace: "
                f"{goalset_index_count} > {self._config.goalset_index_dim}"
            )
        self._goalset_index_count = goalset_index_count
        snapshot = self._snapshot
        snapshot.js_solution.joint_names = candidate.metrics.state.joint_state.joint_names
        snapshot.js_solution.control_space = candidate.metrics.state.joint_state.control_space

        improved = True
        if not self._has_result:
            if self._initial_update_graph is None:
                self._initial_update_graph = create_graph_executor(
                    capture_fn=self._initial_update_graph_impl,
                    device=self._config.device_cfg.device,
                    use_cuda_graph=True,
                    clone_outputs=False,
                )
            any_success_tensor = self._initial_update_graph()
            self._has_result = True
            self._any_success = bool(any_success_tensor.item())
            snapshot.debug_info = self._clone_debug_info(candidate.debug_info)
            self._invalidate_rank()
        else:
            if self._masked_update_graph is None:
                self._masked_update_graph = create_graph_executor(
                    capture_fn=self._masked_update_graph_impl,
                    device=self._config.device_cfg.device,
                    use_cuda_graph=True,
                    clone_outputs=False,
                )
            improved_tensor = self._masked_update_graph()
            improved = bool(improved_tensor.item())
            self._any_success = self._any_success or improved
            if improved:
                self._invalidate_rank()

        next_seed = snapshot.actions.view(
            self._batch_size * self._num_seeds,
            self._config.action_horizon,
            self._config.action_dim,
        )
        return TrajOptResultUpdate(
            improved=improved,
            any_success=self._any_success,
            best_dt=self._best_dt,
            next_seed=next_seed,
        )

    def _initial_update_graph_impl(self) -> torch.Tensor:
        """Reduce and copy the first bound candidate into snapshot storage."""
        candidate_result = self._process_candidate_metrics(self._bound_candidate)
        self._copy_candidate_result(candidate_result)
        return torch.any(self._snapshot.success)

    def _masked_update_graph_impl(self) -> torch.Tensor:
        """Apply one bound candidate through a fixed-shape improvement mask."""
        candidate_result = self._process_candidate_metrics(self._bound_candidate)
        update_mask = torch.logical_and(
            candidate_result.success,
            candidate_result.js_solution.dt <= self._best_dt,
        )
        self._copy_candidate_result_masked(candidate_result, update_mask)
        return torch.any(update_mask)

    @staticmethod
    def _masked_copy(
        destination: torch.Tensor,
        source: torch.Tensor,
        update_mask: torch.Tensor,
    ) -> None:
        """Copy complete seed rows selected by a fixed-shape boolean mask."""
        expanded_mask = update_mask.view(
            *update_mask.shape,
            *((1,) * (destination.ndim - update_mask.ndim)),
        )
        torch.where(expanded_mask, source, destination, out=destination)

    def _copy_candidate_result_masked(
        self,
        candidate_result: _ProcessedTrajOptCandidate,
        update_mask: torch.Tensor,
    ) -> None:
        """Update every retained tensor using one fixed-shape seed mask."""
        snapshot = self._snapshot
        self._masked_copy(snapshot.actions, candidate_result.actions, update_mask)
        self._masked_copy(
            snapshot.js_solution.position,
            candidate_result.js_solution.position,
            update_mask,
        )
        self._masked_copy(
            snapshot.js_solution.velocity,
            candidate_result.js_solution.velocity,
            update_mask,
        )
        self._masked_copy(
            snapshot.js_solution.acceleration,
            candidate_result.js_solution.acceleration,
            update_mask,
        )
        self._masked_copy(
            snapshot.js_solution.jerk,
            candidate_result.js_solution.jerk,
            update_mask,
        )
        self._masked_copy(snapshot.js_solution.dt, candidate_result.js_solution.dt, update_mask)
        self._masked_copy(snapshot.success, candidate_result.success, update_mask)
        self._masked_copy(snapshot.position_error, candidate_result.position_error, update_mask)
        self._masked_copy(snapshot.rotation_error, candidate_result.rotation_error, update_mask)
        self._masked_copy(snapshot.seed_cost, candidate_result.seed_cost, update_mask)
        if self._goalset_index_count > 0:
            self._masked_copy(
                snapshot.goalset_index[..., : self._goalset_index_count],
                candidate_result.goalset_index,
                update_mask,
            )

    @profiler.record_function("trajopt_result_processor/get_interpolation_input")
    def get_interpolation_input(self) -> JointState:
        """Return a borrowed flattened state for one external all-seed interpolation."""
        self._require_result()
        snapshot = self._snapshot
        problem_count = self._batch_size * self._num_seeds
        state_shape = (problem_count, self._config.horizon, self._config.action_dim)
        action_shape = (
            problem_count,
            self._config.action_horizon,
            self._config.action_dim,
        )
        return JointState(
            position=snapshot.js_solution.position.view(state_shape),
            velocity=snapshot.js_solution.velocity.view(state_shape),
            acceleration=snapshot.js_solution.acceleration.view(state_shape),
            jerk=snapshot.js_solution.jerk.view(state_shape),
            joint_names=snapshot.js_solution.joint_names,
            dt=snapshot.js_solution.dt.view(problem_count),
            knot=snapshot.actions.view(action_shape),
            knot_dt=(
                snapshot.js_solution.dt.view(problem_count) * self._config.interpolation_steps
            ),
            control_space=snapshot.js_solution.control_space,
        )

    @profiler.record_function("trajopt_result_processor/finalize")
    def finalize(
        self,
        return_seeds: int,
        interpolated_trajectory: JointState,
        interpolated_last_tstep: torch.Tensor,
        timeopt_success: Optional[torch.Tensor] = None,
        timeopt_duration: Optional[torch.Tensor] = None,
    ) -> TrajOptSolverResult:
        """Rank candidates and gather the externally interpolated all-seed trajectory."""
        self._require_result()
        if return_seeds < 1 or return_seeds > self._num_seeds:
            log_and_raise(
                f"return_seeds must be in [1, {self._num_seeds}], received {return_seeds}"
            )
        if return_seeds != self._return_seeds:
            log_and_raise(
                "return_seeds changed without update_batch_size: "
                f"{return_seeds} != {self._return_seeds}"
            )
        self._validate_interpolation_output(
            interpolated_trajectory,
            interpolated_last_tstep,
        )
        if (timeopt_success is None) != (timeopt_duration is None):
            log_and_raise("TimeOpt success and duration must be provided together")
        if timeopt_duration is not None:
            expected_shape = (self._batch_size, self._num_seeds)
            if timeopt_duration.shape != expected_shape or timeopt_success.shape != expected_shape:
                log_and_raise("TimeOpt success and duration must have shape [batch, seeds]")
        if self._use_cuda_graph:
            return self._finalize_with_cuda_graph(
                interpolated_trajectory,
                interpolated_last_tstep,
                timeopt_success,
                timeopt_duration,
            )

        if not self._is_ranked or timeopt_duration is not None:
            self._rank_final_candidates(timeopt_success, timeopt_duration)
            self._is_ranked = True

        result = self._get_topk_result(
            return_seeds,
            interpolated_trajectory,
            interpolated_last_tstep,
        )
        result.optimized_seeds = result.solution
        result.js_solution = self._get_full_dof_from_solution(result.js_solution)
        result.interpolated_trajectory = self._get_full_dof_from_solution(
            result.interpolated_trajectory
        )
        result.js_solution.knot_dt = result.js_solution.dt * self._config.interpolation_steps
        result.js_solution.knot = result.solution
        return result

    def _finalize_with_cuda_graph(
        self,
        interpolated_trajectory: JointState,
        interpolated_last_tstep: torch.Tensor,
        timeopt_success: Optional[torch.Tensor] = None,
        timeopt_duration: Optional[torch.Tensor] = None,
    ) -> TrajOptSolverResult:
        """Replay ranking and result gathering into borrowed graph-owned outputs."""
        if self._finalize_graph is None:
            self._bound_interpolated_trajectory = interpolated_trajectory
            self._finalize_graph = create_graph_executor(
                capture_fn=self._finalize_graph_impl,
                device=self._config.device_cfg.device,
                use_cuda_graph=True,
                clone_outputs=False,
            )
        self._finalize_graph(interpolated_last_tstep, timeopt_success, timeopt_duration)
        result = self._final_result
        if result is None:
            log_and_raise("TrajOpt result graph did not create a result")
        result.debug_info = self._clone_debug_info(self._snapshot.debug_info)
        return result

    def _finalize_graph_impl(
        self,
        interpolated_last_tstep: torch.Tensor,
        timeopt_success: Optional[torch.Tensor] = None,
        timeopt_duration: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        """Rank and gather fixed-shape result tensors during graph capture."""
        self._rank_final_candidates(timeopt_success, timeopt_duration)
        result = self._get_topk_result(
            self._return_seeds,
            self._bound_interpolated_trajectory,
            interpolated_last_tstep,
        )
        result.optimized_seeds = result.solution
        result.js_solution = self._get_full_dof_from_solution(result.js_solution)
        result.interpolated_trajectory = self._get_full_dof_from_solution(
            result.interpolated_trajectory
        )
        result.js_solution.knot_dt = result.js_solution.dt * self._config.interpolation_steps
        result.js_solution.knot = result.solution
        self._final_result = result
        self._is_ranked = True
        return result.success

    def _rank_final_candidates(
        self,
        timeopt_success: Optional[torch.Tensor],
        timeopt_duration: Optional[torch.Tensor],
    ) -> None:
        """Rank native results by the existing cost or timeopt results by duration."""
        snapshot = self._snapshot
        self._timeopt_duration = timeopt_duration
        if timeopt_duration is None:
            self._final_success = snapshot.success
            self._total_cost, self._seed_rank = TrajOptSolverResult._jit_compute_rank(
                snapshot.js_solution.dt,
                snapshot.js_solution.acceleration,
                snapshot.js_solution.jerk,
                snapshot.seed_cost,
                snapshot.success,
                self._batch_size,
                self._num_seeds,
            )
        else:
            # TimeOpt can repair dynamic infeasibility. Keep endpoint convergence
            # and require a new full rollout check of the timeopt trajectory.
            self._final_success = (
                timeopt_success
                & torch.isfinite(timeopt_duration)
                & (snapshot.position_error < self._config.position_tolerance)
                & (snapshot.rotation_error < self._config.orientation_tolerance)
            )
            self._total_cost = torch.where(self._final_success, timeopt_duration, torch.inf)
            self._seed_rank = torch.argsort(self._total_cost, dim=-1, stable=True)

    def _get_topk_result(
        self,
        return_seeds: int,
        interpolated_trajectory: JointState,
        interpolated_last_tstep: torch.Tensor,
    ) -> TrajOptSolverResult:
        """Gather the requested seeds from the snapshot and transient dense trajectory."""
        snapshot = self._snapshot
        debug_info = self._clone_debug_info(snapshot.debug_info)
        if return_seeds == self._num_seeds:
            total_cost = self._total_cost.clone()
            return TrajOptSolverResult(
                success=self._final_success.clone(),
                solution=snapshot.actions.clone(),
                js_solution=self._clone_joint_state(snapshot.js_solution),
                position_error=snapshot.position_error.clone(),
                rotation_error=snapshot.rotation_error.clone(),
                goalset_index=self._clone_goalset_index(),
                solve_time=0.0,
                total_time=0.0,
                debug_info=debug_info,
                optimized_seeds=None,
                metrics=None,
                position_tolerance=self._config.position_tolerance,
                orientation_tolerance=self._config.orientation_tolerance,
                seed_rank=self._seed_rank.clone(),
                timeopt_duration=(
                    self._timeopt_duration.clone()
                    if self._timeopt_duration is not None else None
                ),
                seed_cost=total_cost,
                batch_size=self._batch_size,
                num_seeds=self._num_seeds,
                total_cost_reshaped=total_cost,
                interpolated_trajectory=self._clone_joint_state(interpolated_trajectory),
                interpolated_last_tstep=interpolated_last_tstep.clone(),
                interpolated_metrics=None,
                minimum_trajectory_dt=self._config.minimum_trajectory_dt,
                maximum_trajectory_dt=self._config.maximum_trajectory_dt,
            )

        topk_seeds = self._seed_rank[:, :return_seeds].view(self._batch_size, return_seeds)
        selected_count = self._batch_size * return_seeds
        flat_indices = self._flat_seed_indices[:selected_count]
        torch.add(
            topk_seeds,
            self._batch_seed_offsets,
            out=flat_indices.view(self._batch_size, return_seeds),
        )

        goalset_index = None
        if self._goalset_index_count > 0:
            goalset_index = self._select_tensor(
                snapshot.goalset_index[..., : self._goalset_index_count],
                flat_indices,
                return_seeds,
            )

        return TrajOptSolverResult(
            success=self._select_tensor(self._final_success, flat_indices, return_seeds),
            solution=self._select_tensor(snapshot.actions, flat_indices, return_seeds),
            js_solution=self._select_joint_state(
                snapshot.js_solution,
                flat_indices,
                return_seeds,
            ),
            position_error=self._select_tensor(
                snapshot.position_error,
                flat_indices,
                return_seeds,
            ),
            rotation_error=self._select_tensor(
                snapshot.rotation_error,
                flat_indices,
                return_seeds,
            ),
            goalset_index=goalset_index,
            solve_time=0.0,
            total_time=0.0,
            debug_info=debug_info,
            optimized_seeds=None,
            metrics=None,
            position_tolerance=self._config.position_tolerance,
            orientation_tolerance=self._config.orientation_tolerance,
            seed_rank=topk_seeds.clone(),
            timeopt_duration=(
                self._select_tensor(self._timeopt_duration, flat_indices, return_seeds)
                if self._timeopt_duration is not None else None
            ),
            seed_cost=self._select_tensor(self._total_cost, flat_indices, return_seeds),
            batch_size=self._batch_size,
            num_seeds=return_seeds,
            total_cost_reshaped=self._total_cost.clone(),
            interpolated_trajectory=self._select_joint_state(
                interpolated_trajectory,
                flat_indices,
                return_seeds,
            ),
            interpolated_last_tstep=self._select_tensor(
                interpolated_last_tstep,
                flat_indices,
                return_seeds,
            ),
            interpolated_metrics=None,
            minimum_trajectory_dt=self._config.minimum_trajectory_dt,
            maximum_trajectory_dt=self._config.maximum_trajectory_dt,
        )

    def _select_tensor(
        self,
        tensor: torch.Tensor,
        flat_indices: torch.Tensor,
        return_seeds: int,
    ) -> torch.Tensor:
        """Select seeds from a tensor shaped ``[batch, seeds, ...]``."""
        tail_shape = tensor.shape[2:]
        flat_tensor = tensor.view(
            self._batch_size * self._num_seeds,
            *tail_shape,
        )
        return torch.index_select(flat_tensor, dim=0, index=flat_indices).view(
            self._batch_size,
            return_seeds,
            *tail_shape,
        )

    def _select_joint_state(
        self,
        joint_state: JointState,
        flat_indices: torch.Tensor,
        return_seeds: int,
    ) -> JointState:
        """Select seeds from every populated tensor in a joint trajectory."""
        return JointState(
            position=self._select_tensor(joint_state.position, flat_indices, return_seeds),
            velocity=self._select_tensor(joint_state.velocity, flat_indices, return_seeds),
            acceleration=self._select_tensor(
                joint_state.acceleration,
                flat_indices,
                return_seeds,
            ),
            jerk=self._select_tensor(joint_state.jerk, flat_indices, return_seeds),
            joint_names=joint_state.joint_names,
            dt=self._select_tensor(joint_state.dt, flat_indices, return_seeds),
            control_space=joint_state.control_space,
        )

    def _copy_candidate_result(
        self,
        candidate_result: _ProcessedTrajOptCandidate,
        batch_indices: Optional[torch.Tensor] = None,
        seed_indices: Optional[torch.Tensor] = None,
        copy_debug: bool = False,
    ) -> None:
        """Copy all or selected candidate fields into preallocated snapshot storage."""
        snapshot = self._snapshot
        candidate_actions = candidate_result.actions
        goalset_index = candidate_result.goalset_index
        goalset_index_count = 0 if goalset_index is None else goalset_index.shape[-1]
        if goalset_index_count > self._config.goalset_index_dim:
            log_and_raise(
                "candidate goalset index dimension exceeds configured workspace: "
                f"{goalset_index_count} > {self._config.goalset_index_dim}"
            )
        if self._has_result and goalset_index_count != self._goalset_index_count:
            log_and_raise(
                "candidate goalset index dimension changed without update_batch_size: "
                f"{goalset_index_count} != {self._goalset_index_count}"
            )
        self._goalset_index_count = goalset_index_count

        if batch_indices is None:
            snapshot.actions.copy_(candidate_actions)
            snapshot.js_solution.copy_(candidate_result.js_solution, allow_clone=False)
            snapshot.success.copy_(candidate_result.success)
            snapshot.position_error.copy_(candidate_result.position_error)
            snapshot.rotation_error.copy_(candidate_result.rotation_error)
            snapshot.seed_cost.copy_(candidate_result.seed_cost)
            if goalset_index_count > 0:
                snapshot.goalset_index[..., :goalset_index_count].copy_(goalset_index)
        else:
            snapshot.actions[batch_indices, seed_indices] = candidate_actions[
                batch_indices, seed_indices
            ]
            copy_joint_state_at_batch_seed_indices(
                snapshot.js_solution,
                candidate_result.js_solution,
                batch_indices,
                seed_indices,
            )
            snapshot.success[batch_indices, seed_indices] = candidate_result.success[
                batch_indices, seed_indices
            ]
            snapshot.position_error[batch_indices, seed_indices] = candidate_result.position_error[
                batch_indices, seed_indices
            ]
            snapshot.rotation_error[batch_indices, seed_indices] = candidate_result.rotation_error[
                batch_indices, seed_indices
            ]
            snapshot.seed_cost[batch_indices, seed_indices] = candidate_result.seed_cost[
                batch_indices, seed_indices
            ]
            if goalset_index_count > 0:
                snapshot.goalset_index[batch_indices, seed_indices, :goalset_index_count] = (
                    goalset_index[batch_indices, seed_indices]
                )

        snapshot.js_solution.joint_names = candidate_result.js_solution.joint_names
        snapshot.js_solution.control_space = candidate_result.js_solution.control_space
        if copy_debug:
            snapshot.debug_info = self._clone_debug_info(candidate_result.debug_info)

    @profiler.record_function("trajopt_result_processor/process_candidate_metrics")
    def _process_candidate_metrics(
        self,
        candidate: TrajOptResultCandidate,
    ) -> _ProcessedTrajOptCandidate:
        """Reduce feasibility and extract terminal convergence fields for each seed."""
        metrics = candidate.metrics
        problem_count = self._batch_size * self._num_seeds
        feasible = self._reduce_feasibility(metrics, "candidate.metrics")
        if candidate.interpolated_metrics is not None:
            interpolated_feasible = self._reduce_feasibility(
                candidate.interpolated_metrics,
                "candidate.interpolated_metrics",
            )
            feasible = torch.logical_and(feasible, interpolated_feasible)

        layout = self._get_convergence_layout(metrics)
        position_values = self._get_terminal_convergence_values(
            metrics,
            layout.position_indices,
        )
        orientation_values = self._get_terminal_convergence_values(
            metrics,
            layout.orientation_indices,
        )
        goalset_index = self._get_terminal_convergence_values(
            metrics,
            layout.goalset_indices,
        )

        zero_error = torch.zeros(
            problem_count,
            device=self._config.device_cfg.device,
            dtype=self._config.device_cfg.dtype,
        )
        position_error = zero_error
        rotation_error = zero_error
        success = feasible
        pose_cost_values = []
        if position_values is not None:
            position_error = torch.amax(position_values, dim=-1)
            success = torch.logical_and(
                success,
                position_error < self._config.position_tolerance,
            )
            pose_cost_values.append(position_values)
        if orientation_values is not None:
            rotation_error = torch.amax(orientation_values, dim=-1)
            success = torch.logical_and(
                success,
                rotation_error < self._config.orientation_tolerance,
            )
            pose_cost_values.append(orientation_values)

        if pose_cost_values:
            pose_cost = (
                pose_cost_values[0]
                if len(pose_cost_values) == 1
                else torch.cat(pose_cost_values, dim=-1)
            )
            seed_cost = torch.sum(pose_cost, dim=-1)
        else:
            seed_cost = zero_error

        batch_seed_shape = (self._batch_size, self._num_seeds)
        if goalset_index is not None:
            goalset_index = goalset_index.view(*batch_seed_shape, goalset_index.shape[-1])
        return _ProcessedTrajOptCandidate(
            actions=metrics.actions.view(
                self._batch_size,
                self._num_seeds,
                self._config.action_horizon,
                self._config.action_dim,
            ),
            js_solution=self._view_candidate_joint_state(metrics.state.joint_state),
            success=success.view(batch_seed_shape),
            position_error=position_error.view(batch_seed_shape),
            rotation_error=rotation_error.view(batch_seed_shape),
            goalset_index=goalset_index,
            seed_cost=seed_cost.view(batch_seed_shape),
            debug_info=candidate.debug_info,
        )

    def _reduce_feasibility(
        self,
        metrics: RolloutMetrics,
        source_name: str,
    ) -> torch.Tensor:
        """Reduce timestep feasibility to one boolean for each flattened seed."""
        problem_count = self._batch_size * self._num_seeds
        feasible = metrics.feasible
        if isinstance(feasible, bool):
            return torch.full(
                (problem_count,),
                feasible,
                device=self._config.device_cfg.device,
                dtype=torch.bool,
            )
        if not isinstance(feasible, torch.Tensor):
            log_and_raise(f"{source_name}.feasible is not set")
        if feasible.shape[0] != problem_count:
            log_and_raise(
                f"{source_name}.feasible batch dimension does not match update_batch_size: "
                f"{feasible.shape[0]} != {problem_count}"
            )
        return torch.all(feasible.view(problem_count, -1), dim=-1)

    def _get_convergence_layout(self, metrics: RolloutMetrics) -> _ConvergenceLayout:
        """Return cached indices for the current stable convergence-name sequence."""
        names = tuple(metrics.convergence.names)
        if names != self._convergence_names:
            self._convergence_names = names
            self._convergence_layout = _ConvergenceLayout(
                position_indices=tuple(
                    index for index, name in enumerate(names) if "position_tolerance" in name
                ),
                orientation_indices=tuple(
                    index for index, name in enumerate(names) if "orientation_tolerance" in name
                ),
                goalset_indices=tuple(
                    index for index, name in enumerate(names) if "goalset_index" in name
                ),
            )
        return self._convergence_layout

    def _get_terminal_convergence_values(
        self,
        metrics: RolloutMetrics,
        indices: tuple[int, ...],
    ) -> Optional[torch.Tensor]:
        """Flatten and concatenate terminal values for selected convergence terms."""
        if not indices:
            return None
        problem_count = self._batch_size * self._num_seeds
        terminal_values = [
            metrics.convergence.values[index][:, -1].reshape(problem_count, -1)
            for index in indices
        ]
        if len(terminal_values) == 1:
            return terminal_values[0]
        return torch.cat(terminal_values, dim=-1)

    def _create_joint_state_workspace(self, horizon: int) -> JointState:
        """Create one shape-managed active-joint trajectory workspace."""
        trajectory_shape = (
            self._batch_size,
            self._num_seeds,
            horizon,
            self._config.action_dim,
        )
        tensor_kwargs = self._config.device_cfg.as_torch_dict()
        position = torch.empty(trajectory_shape, **tensor_kwargs)
        return JointState(
            position=position,
            velocity=torch.empty(trajectory_shape, **tensor_kwargs),
            acceleration=torch.empty(trajectory_shape, **tensor_kwargs),
            jerk=torch.empty(trajectory_shape, **tensor_kwargs),
            joint_names=list(self._config.joint_names),
            dt=torch.empty(
                (self._batch_size, self._num_seeds),
                **tensor_kwargs,
            ),
        )

    def _view_candidate_joint_state(self, joint_state: JointState) -> JointState:
        """View a flattened rollout state as logical batch and seed dimensions."""
        trajectory_shape = (
            self._batch_size,
            self._num_seeds,
            self._config.horizon,
            self._config.action_dim,
        )
        return JointState(
            position=joint_state.position.view(trajectory_shape),
            velocity=joint_state.velocity.view(trajectory_shape),
            acceleration=joint_state.acceleration.view(trajectory_shape),
            jerk=joint_state.jerk.view(trajectory_shape),
            joint_names=(
                joint_state.joint_names
                if joint_state.joint_names is not None
                else list(self._config.joint_names)
            ),
            dt=joint_state.dt.view(self._batch_size, self._num_seeds),
            control_space=joint_state.control_space,
        )

    def _clone_joint_state(self, joint_state: JointState) -> JointState:
        """Clone only tensors required by the returned trajectory contract."""
        return JointState(
            position=joint_state.position.clone(),
            velocity=joint_state.velocity.clone(),
            acceleration=joint_state.acceleration.clone(),
            jerk=joint_state.jerk.clone(),
            joint_names=(
                list(joint_state.joint_names) if joint_state.joint_names is not None else None
            ),
            dt=joint_state.dt.clone(),
            control_space=joint_state.control_space,
        )

    def _clone_goalset_index(self) -> Optional[torch.Tensor]:
        """Clone the populated goal-set index slice, if present."""
        if self._goalset_index_count == 0:
            return None
        return self._snapshot.goalset_index[..., : self._goalset_index_count].clone()

    @staticmethod
    def _clone_debug_info(debug_info: Optional[Dict]) -> Dict:
        """Clone tensor debug values while preserving non-tensor metadata."""
        if debug_info is None:
            return {}
        return {
            key: value.clone() if isinstance(value, torch.Tensor) else value
            for key, value in debug_info.items()
        }

    def _invalidate_rank(self) -> None:
        """Invalidate rank tensors after the retained candidate data changes."""
        self._seed_rank = None
        self._total_cost = None
        self._is_ranked = False

    def _require_shape_initialized(self) -> None:
        if self._best_dt is None or self._snapshot is None:
            log_and_raise(
                "TrajOpt result processor shape is not initialized; call update_batch_size first"
            )

    def _require_result(self) -> None:
        """Require at least one processed candidate."""
        self._require_shape_initialized()
        if not self._has_result:
            log_and_raise("No TrajOpt result candidates were processed before finalization")

    def _validate_candidate_shape(self, candidate: TrajOptResultCandidate) -> None:
        expected_problem_batch = self._batch_size * self._num_seeds
        expected_action_shape = (
            expected_problem_batch,
            self._config.action_horizon,
            self._config.action_dim,
        )
        if candidate.metrics.actions is None:
            log_and_raise("candidate.metrics.actions is not set")
        if candidate.metrics.actions.shape != expected_action_shape:
            log_and_raise(
                "candidate.metrics.actions.shape does not match update_batch_size: "
                f"{candidate.metrics.actions.shape} != {expected_action_shape}"
            )
        if candidate.metrics.state is None or candidate.metrics.state.joint_state is None:
            log_and_raise("candidate.metrics.state.joint_state is not set")
        expected_state_shape = (
            expected_problem_batch,
            self._config.horizon,
            self._config.action_dim,
        )
        if candidate.metrics.state.joint_state.shape != expected_state_shape:
            log_and_raise(
                "candidate joint state shape does not match update_batch_size: "
                f"{candidate.metrics.state.joint_state.shape} != {expected_state_shape}"
            )

    def _validate_interpolation_output(
        self,
        interpolated_trajectory: JointState,
        interpolated_last_tstep: torch.Tensor,
    ) -> None:
        """Validate externally generated interpolation tensors without resizing storage."""
        expected_batch_shape = (self._batch_size, self._num_seeds)
        if interpolated_trajectory.shape[:2] != expected_batch_shape:
            log_and_raise(
                "interpolated trajectory batch dimensions do not match update_batch_size: "
                f"{interpolated_trajectory.shape[:2]} != {expected_batch_shape}"
            )
        if interpolated_trajectory.shape[-1] != self._config.action_dim:
            log_and_raise(
                "interpolated trajectory dof does not match configured action dimension: "
                f"{interpolated_trajectory.shape[-1]} != {self._config.action_dim}"
            )
        if interpolated_last_tstep.shape != expected_batch_shape:
            log_and_raise(
                "interpolated_last_tstep.shape does not match update_batch_size: "
                f"{interpolated_last_tstep.shape} != {expected_batch_shape}"
            )
